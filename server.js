app.post('/api/auth/login', (req, res) => {
  if (!APP_PASSWORD) {
    return res.json({ ok: true });
  }
  const password = String(req.body?.password || '');
  const a = Buffer.from(password);
  const b = Buffer.from(APP_PASSWORD);
  if (a.length !== b.length || !crypto.timingSafeEqual(a, b)) {
    return res.status(401).json({ error: 'Mot de passe incorrect.' });
  }
  const token = makeAuthToken(APP_PASSWORD);
  res.setHeader(
    'Set-Cookie',
    `${COOKIE_NAME}=${encodeURIComponent(token)}; Path=/; HttpOnly; SameSite=Lax; Max-Age=604800`
  );
  return res.json({ ok: true });
});

app.post('/api/auth/logout', (_req, res) => {
  res.setHeader('Set-Cookie', `${COOKIE_NAME}=; Path=/; HttpOnly; SameSite=Lax; Max-Age=0`);
  res.json({ ok: true });
});

app.get('/api/tables', requireAuth, requireDb, async (_req, res) => {
  try {
    const result = await pool.query(
      `SELECT table_schema, table_name
       FROM information_schema.tables
       WHERE table_type = 'BASE TABLE'
         AND table_schema NOT IN ('pg_catalog', 'information_schema')
       ORDER BY
         CASE WHEN table_schema = 'sous_traitance' THEN 0 WHEN table_schema = 'public' THEN 1 ELSE 2 END,
         table_schema,
         table_name`
    );
    res.json({ tables: result.rows });
  } catch (err) {
    res.status(500).json({ error: `Erreur de connexion à la base : ${err.message}` });
  }
});

app.get('/api/tables/:schema/:table/rows', requireAuth, requireDb, async (req, res) => {
  try {
    const { schema, table } = req.params;
    const meta = await getTableMetadata(schema, table);
    if (!meta) {
      return res.status(404).json({ error: 'Table introuvable.' });
    }

    const search = String(req.query.search || '').trim();
    const page = Math.max(1, Number(req.query.page) || 1);
    const pageSize = Math.min(100, Math.max(1, Number(req.query.pageSize) || 25));
    const offset = (page - 1) * pageSize;

    const fullTableName = `${quoteIdent(schema)}.${quoteIdent(table)}`;
    const params = [];
    let whereSql = '';

    if (search && meta.columns.length > 0) {
      params.push(`%${search}%`);
      const searchClauses = meta.columns.map(
        (c) => `CAST(${quoteIdent(c.name)} AS TEXT) ILIKE $1`
      );
      whereSql = `WHERE (${searchClauses.join(' OR ')})`;
    }

    const countQuery = `SELECT COUNT(*)::int AS total FROM ${fullTableName} ${whereSql}`;
    const countResult = await pool.query(countQuery, params);
    const total = countResult.rows[0]?.total || 0;

    const orderBy =
      meta.primaryKeys.length > 0
        ? `ORDER BY ${meta.primaryKeys.map((pk) => `${quoteIdent(pk)} DESC`).join(', ')}`
        : '';

    const selectCols = meta.columns.map((c) => quoteIdent(c.name));
    if (meta.primaryKeys.length === 0) {
      selectCols.push('ctid::text AS "__ctid"');
    }

    const dataParams = [...params, pageSize, offset];
    const limitIdx = params.length + 1;
    const offsetIdx = params.length + 2;

    const rowsQuery = `
      SELECT ${selectCols.join(', ')}
      FROM ${fullTableName}
      ${whereSql}
      ${orderBy}
      LIMIT $${limitIdx} OFFSET $${offsetIdx}
    `;
    const rowsResult = await pool.query(rowsQuery, dataParams);

    const rows = rowsResult.rows.map((row) => {
      const key = {};
      if (meta.primaryKeys.length > 0) {
        for (const pk of meta.primaryKeys) {
          key[pk] = row[pk];
        }
      } else {
        key.__ctid = row.__ctid;
      }
      const data = { ...row };
      delete data.__ctid;
      return { key, data };
    });

    // Fetch brief foreign-key lookup suggestions (up to 200 options per FK)
    const fkOptions = {};
    for (const col of meta.columns) {
      if (!col.foreignKey) continue;
      const fk = col.foreignKey;
      try {
        const refTableSql = `${quoteIdent(fk.schema)}.${quoteIdent(fk.table)}`;
        const refColSql = quoteIdent(fk.column);
        const refMeta = await getTableMetadata(fk.schema, fk.table);
        const labelCol = refMeta?.columns.find(
          (c) => c.name !== fk.column && ['character varying', 'text', 'character'].includes(c.dataType)
        );
        const selectLabel = labelCol
          ? `${refColSql} AS value, CAST(${quoteIdent(labelCol.name)} AS TEXT) AS label`
          : `${refColSql} AS value, CAST(${refColSql} AS TEXT) AS label`;
        const optRes = await pool.query(
          `SELECT ${selectLabel} FROM ${refTableSql} ORDER BY ${refColSql} LIMIT 200`
        );
        fkOptions[col.name] = optRes.rows;
      } catch {
        // Ignore lookup failures and fall back to normal input
      }
    }

    return res.json({
      schema: meta.schema,
      table: meta.table,
      columns: meta.columns,
      primaryKeys: meta.primaryKeys,
      fkOptions,
      rows,
      total,
      page,
      pageSize,
    });
  } catch (err) {
    return res.status(500).json({ error: err.message });
  }
});

app.post('/api/tables/:schema/:table/rows', requireAuth, requireDb, async (req, res) => {
  try {
    const { schema, table } = req.params;
    const meta = await getTableMetadata(schema, table);
    if (!meta) {
      return res.status(404).json({ error: 'Table introuvable.' });
    }

    const payload = req.body?.data || {};
    const insertCols = [];
    const values = [];
    const placeholders = [];

    for (const col of meta.columns) {
      const raw = payload[col.name];
      if (raw === undefined || (raw === '' && col.isAutoGenerated)) {
        continue;
      }
      if (raw === '' && col.defaultValue && !col.nullable) {
        continue;
      }
      const coerced = coerceValue(col, raw);
      if (coerced === undefined) continue;
      insertCols.push(quoteIdent(col.name));
      values.push(coerced);
      placeholders.push(`$${values.length}`);
    }

    const fullTableName = `${quoteIdent(schema)}.${quoteIdent(table)}`;
    const sql =
      insertCols.length > 0
        ? `INSERT INTO ${fullTableName} (${insertCols.join(', ')}) VALUES (${placeholders.join(', ')}) RETURNING *`
        : `INSERT INTO ${fullTableName} DEFAULT VALUES RETURNING *`;

    const result = await pool.query(sql, values);
    return res.status(201).json({ row: result.rows[0] });
  } catch (err) {
    return res.status(400).json({ error: err.message });
  }
});

app.put('/api/tables/:schema/:table/rows', requireAuth, requireDb, async (req, res) => {
  try {
    const { schema, table } = req.params;
    const meta = await getTableMetadata(schema, table);
    if (!meta) {
      return res.status(404).json({ error: 'Table introuvable.' });
    }

    const key = req.body?.key;
    const payload = req.body?.data || {};
    const setClauses = [];
    const values = [];

    for (const col of meta.columns) {
      if (col.isAutoGenerated) continue;
      if (payload[col.name] === undefined) continue;
      const coerced = coerceValue(col, payload[col.name]);
      values.push(coerced);
      setClauses.push(`${quoteIdent(col.name)} = $${values.length}`);
    }

    if (setClauses.length === 0) {
      return res.status(400).json({ error: 'Aucune donnée à modifier.' });
    }

    const where = buildWhereFromKey(meta, key, values.length + 1);
    const fullTableName = `${quoteIdent(schema)}.${quoteIdent(table)}`;
    const sql = `
      UPDATE ${fullTableName}
      SET ${setClauses.join(', ')}
      WHERE ${where.clause}
      RETURNING *
    `;

    const result = await pool.query(sql, [...values, ...where.params]);
    if (result.rowCount === 0) {
      return res.status(404).json({ error: 'Ligne introuvable.' });
    }
    return res.json({ row: result.rows[0] });
  } catch (err) {
    return res.status(400).json({ error: err.message });
  }
});

app.delete('/api/tables/:schema/:table/rows', requireAuth, requireDb, async (req, res) => {
  try {
    const { schema, table } = req.params;
    const meta = await getTableMetadata(schema, table);
    if (!meta) {
      return res.status(404).json({ error: 'Table introuvable.' });
    }

    const where = buildWhereFromKey(meta, req.body?.key, 1);
    const fullTableName = `${quoteIdent(schema)}.${quoteIdent(table)}`;
    const sql = `DELETE FROM ${fullTableName} WHERE ${where.clause}`;
    const result = await pool.query(sql, where.params);
    if (result.rowCount === 0) {
      return res.status(404).json({ error: 'Ligne introuvable.' });
    }
    return res.json({ ok: true });
  } catch (err) {
    return res.status(400).json({ error: err.message });
  }
});

