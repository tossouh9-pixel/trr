const crypto = require('crypto');
const path = require('path');
const express = require('express');
const { Pool } = require('pg');

const app = express();
const PORT = Number(process.env.PORT) || 3000;
const DATABASE_URL = process.env.DATABASE_URL || process.env.DATABASE_PUBLIC_URL || '';
const APP_PASSWORD = process.env.APP_PASSWORD || '';

const isInternalOrLocal =
  !DATABASE_URL ||
  DATABASE_URL.includes('railway.internal') ||
  DATABASE_URL.includes('localhost') ||
  DATABASE_URL.includes('127.0.0.1');

const pool = DATABASE_URL
  ? new Pool({
      connectionString: DATABASE_URL,
      ssl: isInternalOrLocal ? false : { rejectUnauthorized: false },
    })
  : null;

const SESSION_SECRET =
  process.env.SESSION_SECRET ||
  crypto.createHmac('sha256', 'sous-traitance-web').update(APP_PASSWORD || DATABASE_URL || 'dev').digest('hex');
const COOKIE_NAME = 'st_session';

app.use(express.json({ limit: '2mb' }));

function quoteIdent(identifier) {
  return `"${String(identifier).replace(/"/g, '""')}"`;
}

function parseCookies(cookieHeader = '') {
  const cookies = {};
  for (const part of cookieHeader.split(';')) {
    const idx = part.indexOf('=');
    if (idx === -1) continue;
    const key = part.slice(0, idx).trim();
    const val = part.slice(idx + 1).trim();
    if (key) cookies[key] = decodeURIComponent(val);
  }
  return cookies;
}

function makeAuthToken(password) {
  return crypto.createHmac('sha256', SESSION_SECRET).update(`auth:${password}`).digest('hex');
}

function isAuthenticated(req) {
  if (!APP_PASSWORD) return true;
  const cookies = parseCookies(req.headers.cookie);
  const token = cookies[COOKIE_NAME];
  if (!token) return false;
  const expected = makeAuthToken(APP_PASSWORD);
  const a = Buffer.from(token);
  const b = Buffer.from(expected);
  return a.length === b.length && crypto.timingSafeEqual(a, b);
}

function requireAuth(req, res, next) {
  if (isAuthenticated(req)) return next();
  return res.status(401).json({ error: 'Authentification requise.' });
}

function requireDb(req, res, next) {
  if (pool) return next();
  return res.status(500).json({
    error: 'DATABASE_URL manquante. Ajoutez DATABASE_URL = ${{Postgres.DATABASE_URL}} dans Railway Variables.',
  });
}

async function getTableMetadata(schema, table) {
  const tableCheck = await pool.query(
    `SELECT table_schema, table_name
     FROM information_schema.tables
     WHERE table_type = 'BASE TABLE'
       AND table_schema NOT IN ('pg_catalog', 'information_schema')
       AND table_schema = $1
       AND table_name = $2`,
    [schema, table]
  );

  if (tableCheck.rowCount === 0) {
    return null;
  }

  const columnsResult = await pool.query(
    `SELECT
       column_name,
       data_type,
       udt_name,
       is_nullable,
       column_default,
       is_identity,
       ordinal_position
     FROM information_schema.columns
     WHERE table_schema = $1 AND table_name = $2
     ORDER BY ordinal_position`,
    [schema, table]
  );

  const pkResult = await pool.query(
    `SELECT a.attname AS column_name
     FROM pg_index i
     JOIN pg_class c ON c.oid = i.indrelid
     JOIN pg_namespace n ON n.oid = c.relnamespace
     JOIN pg_attribute a ON a.attrelid = c.oid AND a.attnum = ANY(i.indkey)
     WHERE i.indisprimary AND n.nspname = $1 AND c.relname = $2
     ORDER BY array_position(i.indkey, a.attnum)`,
    [schema, table]
  );

  const fkResult = await pool.query(
    `SELECT
       kcu.column_name,
       ccu.table_schema AS ref_schema,
       ccu.table_name AS ref_table,
       ccu.column_name AS ref_column
     FROM information_schema.table_constraints tc
     JOIN information_schema.key_column_usage kcu
       ON tc.constraint_name = kcu.constraint_name AND tc.table_schema = kcu.table_schema
     JOIN information_schema.constraint_column_usage ccu
       ON ccu.constraint_name = tc.constraint_name AND ccu.table_schema = tc.table_schema
     WHERE tc.constraint_type = 'FOREIGN KEY'
       AND tc.table_schema = $1
       AND tc.table_name = $2`,
    [schema, table]
  );

  const fkByColumn = new Map();
  for (const fk of fkResult.rows) {
    fkByColumn.set(fk.column_name, {
      schema: fk.ref_schema,
      table: fk.ref_table,
      column: fk.ref_column,
    });
  }

  const columns = columnsResult.rows.map((col) => {
    const def = col.column_default || '';
    const isAutoGenerated =
      col.is_identity === 'YES' ||
      def.startsWith('nextval(') ||
      def.includes('gen_random_uuid(');

    return {
      name: col.column_name,
      dataType: col.data_type,
      udtName: col.udt_name,
      nullable: col.is_nullable === 'YES',
      defaultValue: col.column_default,
      isAutoGenerated,
      foreignKey: fkByColumn.get(col.column_name) || null,
    };
  });

  return {
    schema,
    table,
    columns,
    primaryKeys: pkResult.rows.map((r) => r.column_name),
  };
}

function coerceValue(col, rawValue) {
  if (rawValue === undefined) return undefined;
  if (rawValue === null || rawValue === '') {
    return col.nullable ? null : '';
  }

  const t = col.dataType.toLowerCase();
  if (t === 'boolean') {
    if (typeof rawValue === 'boolean') return rawValue;
    if (rawValue === 'true' || rawValue === '1') return true;
    if (rawValue === 'false' || rawValue === '0') return false;
    return Boolean(rawValue);
  }

  if (['smallint', 'integer', 'bigint'].includes(t)) {
    const n = Number(rawValue);
    if (!Number.isInteger(n)) {
      throw new Error(`Le champ "${col.name}" doit être un nombre entier.`);
    }
    return n;
  }

  if (['numeric', 'decimal', 'real', 'double precision'].includes(t)) {
    const normalized = String(rawValue).replace(',', '.');
    const n = Number(normalized);
    if (Number.isNaN(n)) {
      throw new Error(`Le champ "${col.name}" doit être un nombre valide.`);
    }
    return n;
  }

  if (t === 'json' || t === 'jsonb') {
    if (typeof rawValue === 'string') {
      try {
        return JSON.stringify(JSON.parse(rawValue));
      } catch {
        throw new Error(`Le champ "${col.name}" doit contenir un JSON valide.`);
      }
    }
    return JSON.stringify(rawValue);
  }

  return rawValue;
}

function buildWhereFromKey(meta, keyObj, startParamIndex = 1) {
  if (!keyObj || typeof keyObj !== 'object') {
    throw new Error('Clé de ligne invalide.');
  }

  if (meta.primaryKeys.length === 0) {
    if (!keyObj.__ctid) {
      throw new Error('Identifiant interne (__ctid) manquant.');
    }
    return {
      clause: `ctid = $${startParamIndex}::tid`,
      params: [String(keyObj.__ctid)],
    };
  }

  const colMap = new Map(meta.columns.map((c) => [c.name, c]));
  const parts = [];
  const params = [];
  let idx = startParamIndex;

  for (const pk of meta.primaryKeys) {
    if (keyObj[pk] === undefined) {
      throw new Error(`Clé primaire "${pk}" manquante.`);
    }
    const col = colMap.get(pk);
    parts.push(`${quoteIdent(pk)} = $${idx}`);
    params.push(col ? coerceValue(col, keyObj[pk]) : keyObj[pk]);
    idx += 1;
  }

  return { clause: parts.join(' AND '), params };
}

